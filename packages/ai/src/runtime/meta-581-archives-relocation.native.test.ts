afterEach(resetResidentPlanPortfolioMemory);
function fixture(){return JSON.parse(readFileSync(new URL("./test-fixtures/meta581-r2-g32-d342-offsite.json",import.meta.url),"utf8"));}
function restore(f:ReturnType<typeof fixture>,input:AiDecisionInputWithDeckCapabilities){
  resetResidentPlanPortfolioMemory();input.planningStateIdentity=buildPlanningStateIdentity(input);
  restoreAiRuntimeCheckpoint(input,input.ownDeckSnapshot!.deckSnapshotId,f.checkpoint.runtime);
  restoreResidentPlanPortfolioMemorySnapshot(input,f.checkpoint.runtime.residentPlanPortfolio);
}
function source(input:AiDecisionInputWithDeckCapabilities){
  return buildActionSemanticCandidates({legalActions:input.legalActions,observerSide:input.side,stateVersion:input.playerView.stateVersion,visibleSourceDefinitionsByInstanceId:visibleSourceDefinitionsByInstanceId(input.playerView),cardSemanticProfilesByDefinitionId:buildActionCardSemanticProfilesByDefinitionId()}).find(c=>c.sourceDefinitionId==="onr_v1_296_off-site-backups"&&c.actionType==="play_operation")!;
}
it("normal native Defense binds and executes the exact Archives agenda recovery and its unchanged choice",()=>{
  const f=fixture(),input=f.checkpoint.input as AiDecisionInputWithDeckCapabilities;
  expect(Object.values(f.checkpoint.validation)).toEqual(Array(9).fill(true));
  expect(f.provenance.checkedStates).toBe(342);
  expect(hashGameState(f.state)).toBe(f.checkpoint.stateHash);
  expect(getLegalActions(f.state,"corp").map(a=>a.actionId).sort()).toEqual(input.legalActions.map(a=>a.actionId).sort());
  restore(f,input);
  const unchanged=JSON.stringify([input.playerView,input.legalActions]);
  const d=chooseAiAction(input);
  expect(d.actionId).toBe(source(input).actionId);
  expect(d.fallbackUsed||d.timeoutUsed).toBe(false);
  const plan=d.decisionDebug!.planFirstDecision!;
  expect(plan.rootPlanInstanceId).toBe("plan:corp.defend_servers:server-defense-portfolio");
  expect(plan.selectedPlan?.moduleId).toBe("corp.defend_servers");
  expect(JSON.stringify([input.playerView,input.legalActions])).toBe(unchanged);
  const p=residentPlanPortfolioSnapshot(input)!;
  const executor=p.instances.find(i=>i.instanceId===p.executorInstanceId)!;
  expect(isExactDefenseRecoveryChoiceOwner(executor,p.selectedActionOrigin,input.playerView.stateVersion)).toBe(true);
  expect(isExactDefenseRecoveryChoiceOwner(executor,p.selectedActionOrigin,input.playerView.stateVersion-1)).toBe(false);
  const origin=p.selectedActionOrigin!;
  if(origin.immediateChoicePolicy!=="select_bound_corp_archives_cards_to_hq")throw Error("exact recovery origin required");
  const wrong={...origin,selectedArchiveCardInstanceIds:["corp_onr_v1_295_night-shift_1"]};
  expect(isExactDefenseRecoveryChoiceOwner(executor,wrong,input.playerView.stateVersion)).toBe(false);
  if(!d.actionId)throw Error("normal source action required");
  const op=applyAction(f.state,{matchId:f.state.matchId,side:"corp",actionId:d.actionId,clientKnownStateVersion:f.state.stateVersion});
  if(!op.ok)throw Error(op.error.message);
  const next={...input,playerView:getPlayerView(op.state,"corp"),legalActions:getLegalActions(op.state,"corp")};
  next.planningStateIdentity=buildPlanningStateIdentity(next);
  const choice=chooseAiAction(next);
  expect(choice.actionId).toBe("corp.resolve_choice");
  expect(choice.selectedChoices).toEqual({choiceId:"v1922_corp_archives_to_hq_342",selectedOptionIds:["card_corp_onr_v1_203_hostile-takeover_2"]});
  expect(choice.fallbackUsed||choice.timeoutUsed).toBe(false);
  if(!choice.selectedChoices)throw Error("bound choices required");
  const resolved=applyAction(op.state,{matchId:op.state.matchId,side:"corp",actionId:choice.actionId!,clientKnownStateVersion:op.state.stateVersion,selectedChoices:choice.selectedChoices});
  if(!resolved.ok)throw Error(resolved.error.message);
  expect(hashGameState(resolved.state)).toBe("fnv1a:7ad71be8");
  const view=getPlayerView(resolved.state,"corp");
  expect(view.own.heapOrArchives.some(c=>c.type==="agenda")).toBe(false);
  expect(view.own.credits).toBe(49);
  expect(view.own.clicks).toBe(2);
  const protection=allocateCorpCentralDefenseFromAiFacts({input:{...next,playerView:view,legalActions:getLegalActions(resolved.state,"corp")}});
  expect(protection.status).toBe("known");
  if(protection.status==="known")expect(protection.evidence.hq.expectedAgendaLoss).toEqual({numerator:1,denominator:6});
});
it.each(["covered_archives","run_prohibited","multiple_agendas","nonterminal","hq_overflow","paid_operation"] as const)("does not invent the bounded relocation with %s",variant=>{
  const f=fixture(),input=f.checkpoint.input as AiDecisionInputWithDeckCapabilities;
  const candidate=source(input);
  if(variant==="covered_archives")input.playerView.servers.find(s=>s.id==="archives")!.ice=[input.playerView.servers.find(s=>s.id==="hq")!.ice[0]!];
  if(variant==="run_prohibited")input.playerView.servers.find(s=>s.id==="archives")!.statuses=[{id:"countercase_run_gate",kind:"run_prohibited",scope:"target_server",reason:"required_corp_activity_during_latest_corp_turn_missing",targetServerId:"archives",sourceCardInstanceId:"countercase_run_gate",sourceAbilityId:"countercase_run_gate",sourceTitle:"Countercase",sourceSide:"corp"}];
  if(variant==="multiple_agendas")input.playerView.own.heapOrArchives.push({...input.playerView.own.heapOrArchives.find(c=>c.type==="agenda")!,instanceId:"countercase_second_agenda"});
  if(variant==="nonterminal")input.playerView.opponent.agendaPoints=0;
  if(variant==="hq_overflow")input.playerView.own.maxHandSize=2;
  if(variant==="paid_operation")input.legalActions.find(a=>a.actionId===candidate.actionId)!.costs=[{clicks:1,credits:1}];
  expect(corpArchivesAgendaRelocationSignal(input,candidate)).toBeUndefined();
});
it("does not spend the last click of an Engine-legal current winning score on recovery",()=>{
  const f=fixture(),state=f.state as GameState;
  const id=state.corp.rd.find(id=>state.cardInstances[id]!.definitionId==="onr_v1_196_corporate-war")!;
  expect(id).toBeDefined();
  state.corp.rd=state.corp.rd.filter(c=>c!==id);
  state.corp.servers.find(s=>s.id==="remote_2")!.root.push(id);
  state.cardInstances[id]!.zone={side:"corp",zone:"serverRoot",serverId:"remote_2"};
  state.cardInstances[id]!.advancementCounters=2;
  state.corp.clicks=1;state.corpBonusAgendaPoints=2;
  const input={...f.checkpoint.input,playerView:getPlayerView(state,"corp"),legalActions:getLegalActions(state,"corp")} as AiDecisionInputWithDeckCapabilities;
  expect(input.playerView.own.agendaPoints).toBe(4);
  const candidate=source(input);
  expect(candidate).toBeDefined();
  expect(corpArchivesAgendaRelocationSignal(input,candidate)).toBeUndefined();
  const advance=input.legalActions.find(a=>a.type==="advance_card"&&a.source===id)!;
  restore(f,input);
  const decision=chooseAiAction(input);
  expect(decision.actionId).toBe(advance.actionId);
  expect(decision.decisionDebug?.planFirstDecision?.selectedPlan?.moduleId).toBe("corp.score_agenda");
  const advanced=applyAction(state,{matchId:state.matchId,side:"corp",actionId:advance.actionId,clientKnownStateVersion:state.stateVersion});
  if(!advanced.ok)throw Error(advanced.error.message);
  const score=getLegalActions(advanced.state,"corp").find(a=>a.type==="score_agenda"&&a.source===id)!;
  const won=applyAction(advanced.state,{matchId:state.matchId,side:"corp",actionId:score.actionId,clientKnownStateVersion:advanced.state.stateVersion});
  if(!won.ok)throw Error(won.error.message);
  expect(won.state.winner).toBe("corp");
});
