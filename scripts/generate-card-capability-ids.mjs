import path from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  GENERATED_CARD_SPECS,
} from "../packages/cards/src/generated/card-spec-import-index.ts";
import {
  CARD_CAPABILITY_IDS,
} from "../packages/cards/src/generated/card-capability-ids.ts";

const output = fileURLToPath(new URL(
  "../packages/cards/src/generated/card-capability-ids.ts",
  import.meta.url,
));

function collectCapabilityKeys(node, keys) {
  if (node === null || typeof node !== "object") return;
  if (typeof node.capabilityKey === "string") {
    if (keys.has(node.capabilityKey))
      throw new Error(`Duplicate capability key ${node.capabilityKey}`);
    keys.add(node.capabilityKey);
  }
  for (const entry of Object.values(node)) collectCapabilityKeys(entry, keys);
}

const capabilities = new Map();
for (const card of GENERATED_CARD_SPECS) {
  const keys = new Set();
  collectCapabilityKeys(card.engine, keys);
  const id = card.identity.cardDefinitionId;
  for (const key of [...keys].sort()) capabilities.set(`${id}:${key}`, [id, key]);
}

// Reserve each existing slot across additions and deletions, including tombstones.
const ledger = CARD_CAPABILITY_IDS.map((pair) => {
  if (pair === null) return null;
  const [id, key] = pair;
  return capabilities.delete(`${id}:${key}`) ? pair : null;
});
ledger.push(...capabilities.values());
const serialized = [
  "// Generated by scripts/generate-card-capability-ids.mjs. ID zero is reserved.",
  "// Slots are append-only and removed capabilities leave tombstones.",
  "export const CARD_CAPABILITY_IDS: readonly (readonly [number, string] | null)[] = [",
  ...ledger.map((pair) =>
    pair === null ? "  null," : `  [${pair[0]}, ${JSON.stringify(pair[1])}],`),
  "];",
  "",
].join("\n");
if (process.argv.includes("--write")) {
  writeFileSync(output, serialized, "utf8");
  process.stdout.write(`Wrote ${path.basename(output)} with ${ledger.length} capability slots.\n`);
} else if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== serialized) {
  throw new Error("Card capability IDs are stale. Run generate:card-capability-ids.");
}
