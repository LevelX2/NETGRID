const ACTION_PRESENTATION_CATALOG: Record<
  AppLocale,
  Record<ActionPresentationMessageKey, string>
> = {
  de: DE_ACTION_PRESENTATION_MESSAGES,
  en: EN_ACTION_PRESENTATION_MESSAGES,
  fr: FR_ACTION_PRESENTATION_MESSAGES,
};

export function normalizeActionPresentationLocale(value: unknown): AppLocale {
  return isAppLocale(value) ? value : DEFAULT_ACTION_PRESENTATION_LOCALE;
}

export function actionPresentationText(
  locale: unknown,
  key: ActionPresentationMessageKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const normalizedLocale = normalizeActionPresentationLocale(locale);
  const template =
    ACTION_PRESENTATION_CATALOG[normalizedLocale][key] ??
    EN_ACTION_PRESENTATION_MESSAGES[key];
  return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (_, name: string) => {
    const value = values[name];
    if (value === undefined) {
      throw new Error(
        `Missing action-presentation value "${name}" for message "${key}".`,
      );
    }
    return String(value);
  });
}

export function actionPresentationNoun(
  locale: unknown,
  noun: "credit" | "action" | "card",
  count: number,
): string {
  const suffix = count === 1 ? "One" : "Other";
  const key = `noun${noun[0]!.toUpperCase()}${noun.slice(1)}${suffix}` as
    | "nounCreditOne"
    | "nounCreditOther"
    | "nounActionOne"
    | "nounActionOther"
    | "nounCardOne"
    | "nounCardOther";
  return actionPresentationText(locale, key);
}
